"""Scene document loading and canonical scene hashing."""

from __future__ import annotations

from dataclasses import asdict
import hashlib
import json
from pathlib import Path
from typing import Any, Mapping, Optional, Union

from ..contracts import SceneId
from .parsing import scene_from_mapping
from .schema import SceneAsset, SceneSpec


_SCENE_DIR = Path(__file__).resolve().parent


def load_scene(scene_id: Union[SceneId, str], root: Optional[Path] = None) -> SceneSpec:
    """Load one immutable scene and verify its declared geometry hash."""

    normalized_id = scene_id if isinstance(scene_id, SceneId) else SceneId(scene_id)
    scene_root = Path(root) if root is not None else _SCENE_DIR
    path = scene_root / f"{normalized_id.value}.yaml"
    raw = _read_mapping(path)
    scene = scene_from_mapping(raw)
    if scene.scene_id is not normalized_id:
        raise ValueError(f"{path}: declares scene {scene.scene_id.value}, expected {normalized_id.value}")
    computed = scene_hash_from_mapping(raw)
    if computed != scene.scene_hash:
        raise ValueError(
            f"{path}: scene hash mismatch (declared {scene.scene_hash}, computed {computed})"
        )
    return scene


def compute_scene_hash(scene: SceneSpec) -> str:
    """Recompute the geometry/configuration hash from an immutable scene."""

    payload = asdict(scene)
    payload["scene_id"] = scene.scene_id.value
    payload["derivation"]["source_scene"] = (
        scene.derivation.source_scene.value if scene.derivation.source_scene is not None else None
    )
    return scene_hash_from_mapping(payload)


def directed_route_document(scene: SceneSpec) -> dict[str, Any]:
    """Emit the exact document shape accepted by the frozen V83 route loader.

    Visibility and authority declarations remain hash-bound in ``SceneSpec``
    but are intentionally not injected into this payload: V83 accepts only
    connected-route geometry, while its model-facing renderer separately
    declares that the model owns primitive, coordination, role, and parameter
    choices.
    """

    route = scene.route
    return {
        "schema_version": route.schema_version,
        "kind": route.kind,
        "scene_id": route.scene_id,
        "mission_topology": list(route.mission_topology),
        "progress_gates": [asdict(gate) for gate in route.progress_gates],
        "segments": [asdict(segment) for segment in route.segments],
    }


def scene_hash_from_mapping(raw: Mapping[str, Any]) -> str:
    """Hash structural scene data, excluding evidence and the digest itself."""

    payload = {
        key: raw[key]
        for key in (
            "schema_version",
            "scene_id",
            "label",
            "protocol_invariant_ref",
            "terminal_predicate_ref",
            "asset",
            "initial_state",
            "target",
            "corridor",
            "camera",
            "route",
            "derivation",
        )
    }
    encoded = json.dumps(
        _normalize_canonical(payload),
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=True,
        allow_nan=False,
    )
    return hashlib.sha256(encoded.encode("utf-8")).hexdigest()


def compute_asset_composite_hash(asset: SceneAsset) -> str:
    """Bind generated bytes to the pinned source and realization operations."""

    if asset.execution_sha256 is None:
        raise ValueError("cannot compute a realized-asset composite hash before generation")
    payload = {
        "source_sha256": asset.source_sha256,
        "realization": asset.realization,
        "realization_parameters": [asdict(item) for item in asset.realization_parameters],
        "execution_sha256": asset.execution_sha256,
    }
    encoded = json.dumps(
        payload,
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=True,
        allow_nan=False,
    )
    return hashlib.sha256(encoded.encode("utf-8")).hexdigest()


def _read_mapping(path: Path) -> Mapping[str, Any]:
    try:
        payload = json.loads(
            path.read_text(encoding="utf-8"),
            parse_constant=_reject_nonfinite_json_constant,
            object_pairs_hook=_object_without_duplicate_keys,
        )
    except FileNotFoundError as exc:
        raise FileNotFoundError(f"missing scene registry entry: {path}") from exc
    except json.JSONDecodeError as exc:
        raise ValueError(
            f"{path} must use the repository's JSON-compatible YAML subset: {exc}"
        ) from exc
    except ValueError as exc:
        raise ValueError(
            f"{path} must use strict finite JSON without duplicate keys: {exc}"
        ) from exc
    if not isinstance(payload, dict):
        raise ValueError(f"{path} must contain a top-level object")
    return payload


def _normalize_canonical(value: Any) -> Any:
    """Make semantically identical JSON integers/floats hash identically."""

    if isinstance(value, bool) or value is None or isinstance(value, str):
        return value
    if isinstance(value, (int, float)):
        return float(value)
    if isinstance(value, dict):
        if set(value) == {"x", "y"}:
            return [
                _normalize_canonical(value["x"]),
                _normalize_canonical(value["y"]),
            ]
        if set(value) == {"x", "y", "z"}:
            return [
                _normalize_canonical(value["x"]),
                _normalize_canonical(value["y"]),
                _normalize_canonical(value["z"]),
            ]
        return {key: _normalize_canonical(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [_normalize_canonical(item) for item in value]
    return value


def _object_without_duplicate_keys(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate JSON object key: {key}")
        result[key] = value
    return result


def _reject_nonfinite_json_constant(value: str) -> None:
    raise ValueError(f"non-finite JSON constant is forbidden: {value}")


