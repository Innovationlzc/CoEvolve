"""Object and robot path planning utilities."""

from __future__ import annotations

from .models import Pose2D, RoleAssignment, SceneGraph, TransportPlan, wrap_angle
from .utils.geometry import offset_path


def plan_object_path(scene: SceneGraph) -> list[Pose2D]:
    """Plan a small SE(2) path for the object center.

    The first implementation is intentionally deterministic and conservative:
    start -> pre-gate alignment -> gate center -> target.
    """

    start = scene.movable_object.pose
    target = scene.target.pose
    path = [start]

    if scene.scene_id == "manual_two_g1_box_push_layout":
        corridor_x = 1.55
        path.extend(
            [
                Pose2D(corridor_x, start.y, start.yaw),
                Pose2D(corridor_x, target.y, target.yaw),
                Pose2D(target.x, target.y, target.yaw),
            ]
        )
        return path

    if scene.scene_id == "stage1_two_g1_carry_wall":
        mid_y = start.y + 0.5 * (target.y - start.y)
        path.extend(
            [
                Pose2D(start.x, mid_y, start.yaw),
                Pose2D(target.x, target.y, target.yaw),
            ]
        )
        return path

    if scene.gate is not None:
        gate = scene.gate
        pre_gate = Pose2D(
            x=gate.center.x - 0.75,
            y=gate.center.y,
            yaw=gate.axis_yaw,
        )
        gate_pose = Pose2D(gate.center.x, gate.center.y, gate.axis_yaw)
        path.extend([pre_gate, gate_pose])

    final_yaw = target.yaw
    if scene.gate is not None:
        final_yaw = wrap_angle(scene.gate.axis_yaw)
    path.append(Pose2D(target.x, target.y, final_yaw))
    return path


def plan_transport_paths(scene: SceneGraph, roles: RoleAssignment) -> TransportPlan:
    """Plan object COM path plus role-conditioned robot paths.

    The object path is the shared task-space reference. Each robot receives a
    path generated by applying its role offset in the object's local frame at
    every waypoint. This keeps planning explicit for both the payload and each
    robot, which is required for tight two-humanoid transport.
    """

    object_path = plan_object_path(scene)
    robot_paths = {
        robot_id: offset_path(object_path, roles.offsets[robot_id])
        for robot_id in roles.roles
        if robot_id in roles.offsets
    }
    return TransportPlan(
        object_path=object_path,
        robot_paths=robot_paths,
        role_offsets=roles.offsets,
        sync_predicates=[
            "both_agents_reach_phase_waypoint",
            "front_back_distance_error < 0.08m",
            "object_yaw_error_within_phase_tolerance",
        ],
    )
